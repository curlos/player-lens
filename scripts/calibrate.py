"""Calibration run: simulate many seeds headless and compare means to the benchmark bands.

Run from the repo root:  python scripts/calibrate.py [--seeds 200] [--report docs/validation-report.md]

Code only, zero LLM calls. Uses all CPU cores; each seed is independent and deterministic.
"""

from __future__ import annotations

import argparse
import statistics
import sys
from collections import Counter
from multiprocessing import Pool
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sim.engine import simulate  # noqa: E402
from sim.models import load_world  # noqa: E402
from sim.stats import BENCHMARKS, match_stats  # noqa: E402

_WORLD = None


def _run(seed: int) -> dict:
    global _WORLD
    if _WORLD is None:
        _WORLD = load_world(ROOT / "data" / "world.json")
    r = simulate(_WORLD, seed)
    return match_stats(r.events, r.xy, r.sent_off)


def run_seeds(seeds: list[int]) -> list[dict]:
    with Pool() as pool:
        return pool.map(_run, seeds, chunksize=4)


def summarize(results: list[dict]) -> str:
    """Markdown table of mean, SD and band for each benchmark row, plus extra rows."""
    lines = ["| Metric | Mean | SD | Target | In band |", "| --- | --- | --- | --- | --- |"]
    for key, (lo, hi, label) in BENCHMARKS.items():
        vals = [r[key] for r in results]
        mean, sd = statistics.mean(vals), statistics.pstdev(vals)
        fmt = (lambda v: f"{v * 100:.1f}%") if key == "pass_completion" else (lambda v: f"{v:.2f}")
        target = f"{fmt(lo)}-{fmt(hi)}"
        lines.append(f"| {label} | {fmt(mean)} | {fmt(sd)} | {target} | {'yes' if lo <= mean <= hi else 'no'} |")
    extra = {
        "Goals AZC": [r["score"]["azc"] for r in results], "Goals RDM": [r["score"]["rdm"] for r in results],
        "Pressures AZC": [r["pressures"]["azc"] for r in results], "Pressures RDM": [r["pressures"]["rdm"] for r in results],
        "Distance AZC (km)": [r["distance_by_team"]["azc"] for r in results],
        "Distance RDM (km)": [r["distance_by_team"]["rdm"] for r in results],
        "xG (both)": [r["xg"] for r in results], "Yellow cards": [r["yellows"] for r in results],
        "Red cards": [r["reds"] for r in results], "Penalties": [r["penalties"] for r in results],
        "Offsides": [r["offsides"] for r in results], "Corners": [r["corners"] for r in results],
        "Injuries": [r["injuries"] for r in results],
    }
    lines += ["", "| Extra | Mean | SD |", "| --- | --- | --- |"]
    for label, vals in extra.items():
        lines.append(f"| {label} | {statistics.mean(vals):.2f} | {statistics.pstdev(vals):.2f} |")
    # Poisson check: variance close to the mean means goals per team look Poisson.
    lines += ["", "Goals per team, variance / mean (about 1 means roughly Poisson): "
              + ", ".join(f"{t.upper()} {statistics.pvariance(v) / max(1e-9, statistics.mean(v)):.2f}"
                          for t, v in (("azc", extra["Goals AZC"]), ("rdm", extra["Goals RDM"])))]
    outcomes = Counter("AZC win" if r["score"]["azc"] > r["score"]["rdm"] else "RDM win" if r["score"]["rdm"] > r["score"]["azc"]
                       else "draw" for r in results)
    lines.append("Results: " + ", ".join(f"{k} {v / len(results) * 100:.0f}%" for k, v in sorted(outcomes.items())))
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seeds", type=int, default=200)
    parser.add_argument("--start", type=int, default=1)
    parser.add_argument("--report", type=Path, default=None, help="write a markdown report here")
    args = parser.parse_args()
    seeds = list(range(args.start, args.start + args.seeds))
    results = run_seeds(seeds)
    table = summarize(results)
    print(table)
    if args.report:
        header = (f"# Validation report\n\nGenerated by `python scripts/calibrate.py --start {args.start} --seeds {args.seeds} "
                  f"--report {args.report}` "
                  f"over seeds {seeds[0]}-{seeds[-1]} with the committed `data/world.json`. Code only, no LLM calls.\n"
                  "Targets are the Premier League bands in ARCHITECTURE section 3.\n\n")
        args.report.write_text(header + table + "\n", encoding="utf-8")
        print(f"wrote {args.report}")


if __name__ == "__main__":
    main()
